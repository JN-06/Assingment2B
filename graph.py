import networkx as nx

# =========================
# NODES
# =========================
NODES = [
    3120, 3122, 3126, 3180,
    4030, 4032, 4034, 4035,
    4040, 4043
]

# =========================
# EDGES (TRAFFIC LINKS)
# =========================
EDGES = [
    (3120, 3122),
    (3120, 4030),
    (3120, 3180),
    (3122, 3126),
    (3122, 4034),
    (3126, 4032),
    (4032, 4043),
    (4030, 4034),
    (4034, 4043),
    (4040, 4034),
    (4040, 4043),
    (4035, 4040),
    (3180, 4040),
    (3180, 4030),
    (3180, 4035),

    # Reverse paths
    (4043, 4032),
    (4043, 4034),
    (4043, 4040),
    (4032, 3126),
    (3126, 3122),
    (3122, 3120),
    (4034, 3122),
    (4034, 4030),
    (4034, 4040),
    (4030, 3120),
    (4030, 3180),
    (4040, 3180),
    (4040, 4035),
    (4035, 3180),
    (3180, 3120),
]

# =========================
# BUILD GRAPH
# =========================
def build_graph():
    G = nx.DiGraph()

    positions = {
        3120: (0, 2),
        3122: (1, 2),
        3126: (2, 2),
        3180: (0, 0),
        4030: (1, 1),
        4032: (3, 2),
        4034: (2, 1),
        4035: (1, -1),
        4040: (2, 0),
        4043: (3, 1)
    }

    for node in NODES:
        G.add_node(node, pos=positions[node])

    for u, v in EDGES:
        G.add_edge(u, v, weight=1)

    return G


# =========================
# TEST
# =========================
if __name__ == "__main__":
    G = build_graph()

    print("Nodes:")
    print(G.nodes())

    print("\nEdges:")
    for edge in G.edges(data=True):
        print(edge)